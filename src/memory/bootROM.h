/**
 * @file bootROM.h
 * @brief Boot ROM for an
 */
#pragma once

#include "DEFINES.h"

// clang-format off

// DMG Boot ROM sourced and transcribed from: https://www.neviksti.com/DMG/DMG_ROM.asm
const byte m_boot_rom[] = {
    // Setup Stack
    0x31, 0xFF, 0xFE, // ADDR: 0x0000 | LD SP, 0xFFFE
    
    // Zero the memory from 0x8000-0x9FFF (VRAM)
    0xAF,             // ADDR: 0x0003 | XOR A
    0x21, 0x9F, 0xFF, // ADDR: 0x0004 | LD HL, 0x9FFF
// Addr_0007:
    0x32,             // ADDR: 0x0007 | LD (HL-), A
    0xCB, 0x7C,       // ADDR: 0x0008 | BIT 7, H
    0x20, 0xFB,       // ADDR: 0x000A | JR NZ, Addr_0007 | (-5)

    // Setup Audio
    0x21, 0xFF, 0x26, // ADDR: 0x000C | LD HL, 0xFF26
    0x0E, 0x11,       // ADDR: 0x000F | LD C, 0x11
    0x3E, 0x80,       // ADDR: 0x0011 | LD A, 0x80
    0x32,             // ADDR: 0x0013 | LD (HL-), A
    0xE2,             // ADDR: 0x0014 | LD (0xFF00+C), A
    0x0C,             // ADDR: 0x0015 | INC C
    0x3E, 0xF3,       // ADDR: 0x0016 | LD A, 0xF3
    0xE2,             // ADDR: 0x0018 | LD (0xFF00+C), A
    0x32,             // ADDR: 0x0019 | LD (HL-), A
    0x3E, 0x77,       // ADDR: 0x001A | LD A, 0x77
    0x77,             // ADDR: 0x001C | LD (HL), A

    // Setup BG palette
    0x3E, 0xFC,       // ADDR: 0x001D | LD A, 0xFC
    0xE0, 0x47,       // ADDR: 0x001F | LD (0xFF00+0x47), A

    // Convert and load logo data from cart into Video RAM
    0x11, 0x01, 0x04, // ADDR: 0x0021 | LD DE, 0x0104
    0x21, 0x80, 0x10, // ADDR: 0x0024 | LD HL, 0x8010
// Addr_0027:
    0x1A,             // ADDR: 0x0027 | LD A, (DE)
    0xCD, 0x00, 0x95, // ADDR: 0x0028 | CALL 0x0095
    0xCD, 0x00, 0x96, // ADDR: 0x002B | CALL 0x0096
    0x13,             // ADDR: 0x002E | INC DE
    0x7B,             // ADDR: 0x002F | LD A, E
    0xFE, 0x34,       // ADDR: 0x0030 | CP A, 0x34
    0x20, 0xF3,       // ADDR: 0x0032 | JR NZ, Addr_0027 | (-13)

    // Load 8 additional bytes into Video RAM
    0x11, 0x00, 0xD8, // ADDR: 0x0034 | LD DE, 0x00D8
    0x06, 0x08,       // ADDR: 0x0037 | LD B, 0x08
// Addr_0039:
    0x1A,             // ADDR: 0x0039 | LD A, (DE)
    0x13,             // ADDR: 0x003A | INC DE
    0x22,             // ADDR: 0x003B | LD (HL+), A
    0x23,             // ADDR: 0x003C | INC HL
    0x05,             // ADDR: 0x003D | DEC B
    0x20, 0xF9,       // ADDR: 0x003E | JR NZ, Addr_0039 | (-7)

    // Setup background tilemap
    0x3E, 0x19,       // ADDR: 0x0040 | LD A, 0x19
    0xEA, 0x99, 0x10, // ADDR: 0x0042 | LD (0x9910), A
    0x21, 0x99, 0x2F, // ADDR: 0x0045 | LD HL, 0x992F
// Addr_0048:
    0x0E, 0x0C,       // ADDR: 0x0048 | LD C, 0x0C
// Addr_004A:
    0x3D,             // ADDR: 0x004A | DEC A,
    0x28, 0x08,       // ADDR: 0x004B | JR Z, Addr_0055 | (+8)
    0x32,             // ADDR: 0x004D | LD (HL-), A
    0x0D,             // ADDR: 0x004E | DEC C
    0x20, 0xF9,       // ADDR: 0x004F | JR NZ, Addr_004A | (-7)
    0x2E, 0x0F,       // ADDR: 0x0051 | LD L, 0x0F
    0x18, 0xF3,       // ADDR: 0x0053 | JR Addr_0048 | (-13)

// ==== Scroll logo on screen and play logo sound ====
// Addr_0055:
    // Initialize scroll count, H=0
    0x67,             // ADDR: 0x0055 | LD H, A
    0x3E, 0x64,       // ADDR: 0x0056 | LD A, 0x64
    // set loop count, D=0x64
    0x57,             // ADDR: 0x0058 | LD D, A
    // Set vertical scroll register
    0xE0, 0x42,       // ADDR: 0x0059 | LD (0xFF00+0x42), A
    0x3E, 0x91,       // ADDR: 0x005B | LD A, 0x91
    // Turn on LCD, showing Background
    0xE0, 0x40,       // ADDR: 0x005D | LD (0xFF00+0x40), A
    // Set B=1
    0x04,             // ADDR: 0x005F | INC B
// Addr_0060:
    0x1E, 0x02,       // ADDR: 0x0060 | LD E, 0x02
// Addr_0062:
    0x0E, 0x0C,       // ADDR: 0x0062 | LD C, 0x0C
// Addr_0064:
    // Wait for screen frame
    0xF0, 0x44,       // ADDR: 0x0064 | LD A, (0xFF00+0x44)
    0xFE, 0x90,       // ADDR: 0x0066 | CP A, 0x90
    0X20, 0XFA,       // ADDR: 0x0068 | JR NZ, Addr_0064 | (-6)
    0x0D,             // ADDR: 0x006A | DEC C
    0x20, 0xF7,       // ADDR: 0x006B | JR NZ, Addr_0064 | (-9)
    0x1D,             // ADDR: 0x006D | DEC E
    0x20, 0xF2,       // ADDR: 0x006E | JR NZ, Addr_0062 | (-14)

    0x0E, 0x13,       // ADDR: 0x0070 | LD C, 0x13
    // increment scroll count
    0x24,             // ADDR: 0x0072 | INC H
    0x7C,             // ADDR: 0x0073 | LD A, H
    0x1E, 0x83,       // ADDR: 0x0074 | LD E, 0x83
    // 0x62 counts in, play sound #1
    0xFE, 0x62,       // ADDR: 0x0076 | CP A, 0x62
    0x28, 0x06,       // ADDR: 0x0078 | JR Z, Addr_0080 | (+6)
    0x1E, 0xC1,       // ADDR: 0x007A | LD E, 0xC1
    0xFE, 0x64,       // ADDR: 0x007C | CP A, 0x64
    // 0x64 counts in, play sound #2
    0x20, 0x06,       // ADDR: 0x007E | JR NZ, Addr_0086 | (+6)
// Addr_0080:
    // play sound
    0x7B,             // ADDR: 0x0080 | LD A, E
    0xE2,             // ADDR: 0x0081 | LD (0xFF00+C), A
    0x0C,             // ADDR: 0x0082 | INC C
    0x3E, 0x87,       // ADDR: 0x0083 | LD A, 0x87
    0xE2,             // ADDR: 0x0085 | LD (0xFF00+C), A
// Addr_0086:
    0xF0, 0x42,       // ADDR: 0x0086 | LD A, (0xFF00+0x42)
    0x90,             // ADDR: 0x0088 | SUB A, B
    // scroll logo up if B=1
    0xE0, 0x42,       // ADDR: 0x0089 | LD (0xFF00+0x42), A
    0x15,             // ADDR: 0x008B | DEC D
    0x20, 0xD2,       // ADDR: 0x008C | JR NZ, Addr_0060 | (-46)

    // set B=0 first time
    0x05,             // ADDR: 0x008E | DEC B
    // ... next time, cause jump to "Nintendo Logo check"
    0x20, 0x4F,       // ADDR: 0x008F | JR NZ, Addr_00E0 | (+79)

    // use scrolling loop to pause
    0x16, 0x20,       // ADDR: 0x0091 | LD D, 0x20
    0x18, 0xCB,       // ADDR: 0x0093 | JR Addr_0060 | (-53)

// ==== Graphic routine ====

    // "Double up" all the bits of the graphics data and store in Video RAM
    0x4F,             // ADDR: 0x0095 | LD C, A
    0x06, 0x04,       // ADDR: 0x0096 | LD B, 0x04
// Addr_0098:
    0xC5,             // ADDR: 0x0098 | PUSH BC
    0xCB, 0x11,       // ADDR: 0x0099 | RL C
    0x17,             // ADDR: 0x009b | RLA
    0xC1,             // ADDR: 0x009c | POP BC
    0xCB, 0x11,       // ADDR: 0x009d | RL C
    0x17,             // ADDR: 0x009f | RLA
    0x05,             // ADDR: 0x00A0 | DEC B
    0x20, 0xF5,       // ADDR: 0x00A1 | JR NZ, Addr_0098 | (-11)
    0x22,             // ADDR: 0x00A3 | LD (HL+), A
    0x23,             // ADDR: 0x00A4 | INC HL
    0x22,             // ADDR: 0x00A5 | LD (HL+), A
    0x23,             // ADDR: 0x00A6 | INC HL
    0xC9,             // ADDR: 0x00A7 | RET

// Addr_00A8:
    // Nintendo Logo
    0xCE, 0xED, 0x66, 0x66, 0xCC, 0x0D, 0x00, 0x0B, 0x03, 0x73, 0x00, 0x83, 0x00, 0x0C, 0x00, 0x0D, 
    0x00, 0x08, 0x11, 0x1F, 0x88, 0x89, 0x00, 0x0E, 0xDC, 0xCC, 0x6E, 0xE6, 0xDD, 0xDD, 0xD9, 0x99, 
    0xBB, 0xBB, 0x67, 0x63, 0x6E, 0x0E, 0xEC, 0xCC, 0xDD, 0xDC, 0x99, 0x9F, 0xBB, 0xB9, 0x33, 0x3E,

// Addr_00D8:
    // More video data
    0x3C, 0x42, 0xB9, 0xA5, 0xB9, 0xA5, 0x42, 0x3C,

// ==== Nintendo logo comparison routine =====

// Addr_00E0:
    // point HL to Nintendo logo in cart
    0x21, 0x01, 0x04, // ADDR: 0x00E0 | LD HL, 0x0104
    // point DE to Nintendo logo in DMG rom
    0x11, 0x00, 0xA8, // ADDR: 0x00E3 | LD DE, 0x00A8

// Addr_00E6:
    0x1A,             // ADDR: 0x00E6 | LD A, (DE)
    0x13,             // ADDR: 0x00E7 | INC DE
    // compare logo data in cart to DMG rom
    // if not a match, lock up here
    0xBE,             // ADDR: 0x00E8 | CP A, (HL)
    0x20, 0xFE,       // ADDR: 0x00E9 | JR NZ, 0xFE | (-2)
    0x23,             // ADDR: 0x00EB | INC HL
    0x7D,             // ADDR: 0x00EC | LD A, L
    // Do this for 0x30 bytes
    0xFE, 0x34,       // ADDR: 0x00ED | CP A, 0x34
    0x20, 0xF5,       // ADDR: 0x00EF | JR NZ, Addr_00E6 | (-11)

    0x06, 0x19,       // ADDR: 0x00F1 | LD B, 0x19
    0x78,             // ADDR: 0x00F3 | LD A, B
// Addr_00F4:
    0x86,             // ADDR: 0x00F4 | ADD A, (HL)
    0x23,             // ADDR: 0x00F5 | INC HL
    0x05,             // ADDR: 0x00F6 | DEC B
    0x20, 0xFB,       // ADDR: 0x00F7 | JR NZ, Addr_00F4 | (-5)
    0x86,             // ADDR: 0x00F9 | ADD A, (HL)
    // if 0x19 + bytes from 0x0134-0x014D don't add to 0x00
    // ... lock up
    0x20, 0xFE,       // ADDR: 0x00FA | JR NZ, 0xFE | (-2)

    0x3E, 0x01,       // ADDR: 0x00FC | LD A, 0x01
    0xE0, 0x50        // ADDR: 0x00FE | LD (0xFF00+0x50), A 
};
// clang-format on
